#!/usr/bin/env python3
"""Render the per-seat write-scope table (docs/SEAT-WRITE-SCOPES.md).

#78: every seat runs with `external_directory: deny` and cwd-relative
`path_write` globs, so a mission's files must sit under the globs of the
seats that will touch them. This table is the operator's lookup for that,
generated from fleet/fleet.yaml so it cannot drift silently
(tests/test_seat_scopes.py fails when the committed copy is stale).

Usage:
  python3 scripts/seat-scopes.py            # print to stdout
  python3 scripts/seat-scopes.py --write    # rewrite docs/SEAT-WRITE-SCOPES.md
  python3 scripts/seat-scopes.py --check    # exit 1 if the committed copy is stale
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FLEET = ROOT / "fleet/fleet.yaml"
OUT = ROOT / "docs/SEAT-WRITE-SCOPES.md"

HEADER = """\
# Seat write scopes

<!-- Generated by scripts/seat-scopes.py from fleet/fleet.yaml. Do not edit by hand. -->

Every seat's `path_write` globs are relative to the workspace it was launched
in (`rig up ... --cwd <workspace>`), and `external_directory` is `deny`. A
mission whose files sit outside these globs cannot be written by any seat:
the seat will block honestly, not work around it (#78).

Place mission files so each slice lands under its owning seat's globs. A new
top-level folder that no row below covers is writable by no seat.

To give a mission its own workspace without bouncing the fleet, move only
the seats it needs (OpenRig 0.7.5+; see docs/USER_GUIDE.md, "Refreshing or
re-homing one seat"):

```bash
rig seat set-cwd <seat> --cwd /abs/path/to/mission-workspace --reason "<mission>"
rig seat launch <seat> --fresh --stop --reason "<mission>: adopt workspace"
```

Inside that workspace the same relative globs apply. Fresh launch starts a
blank conversation; queue rows and seat identity are kept.

`*` in a glob also matches `/`, so `src/*` covers `src/a/b.c`. Rows marked
read-only charter write reports only; they do not author code.

In `heretek-omni-fleet` a seat keeps the name below (`<seat>@heretek-omni-fleet`),
except the command pod: {command}.

| Seat | Rig | Writable (relative to the workspace) |
|---|---|---|
"""


def render() -> str:
    fleet = yaml.safe_load(FLEET.read_text())
    roles = fleet["roles"]
    core = fleet["omni"]["core_pod"]
    command = ", ".join(
        f"`{core['id']}-{m}` uses the `{roles[m]['session'].split('@', 1)[0]}` row"
        for m in core["members"]
    )
    rows = []
    for rid, role in sorted(roles.items(), key=lambda kv: (kv[1]["rig"], kv[0])):
        seat = role["session"].split("@", 1)[0]
        globs = role["permissions"]["path_write"]
        scope = ", ".join(f"`{g}`" for g in globs) or "_none_"
        if role.get("readonly_charter"):
            scope += " (read-only charter)"
        rows.append(f"| `{seat}` | {role['rig']} | {scope} |\n")
    return HEADER.format(command=command) + "".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.write:
        OUT.write_text(text)
    elif args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/seat-scopes.py --write", file=sys.stderr)
            return 1
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
